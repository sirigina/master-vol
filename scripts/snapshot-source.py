def closes():
    out = []
    for chunk in CLOSES.replace("\n", "|").split("|"):
        chunk = chunk.strip()
        if not chunk:
            continue
        d, c = chunk.split()
        out.append([d, float(c)])
    return out

def implied_rate():
    """Back out the financing rate from put-call parity (no dividend before expiry)."""
    T = DTE / 365
    rs = []
    for k in (760, 765, 770, 775, 780):
        c, p = CALLS[k][2], PUTS[k][2]
        pv_k = SPOT - (c - p)
        rs.append(-math.log(pv_k / k) / T)
    return statistics.median(rs)

